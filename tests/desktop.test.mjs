import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { DesktopProfiles } from '../electron/desktop.mjs';

async function fixture(t, overrides = {}) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'claude-desktop-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const liveDir = path.join(root, 'Claude');
  const dataDir = path.join(root, 'Switch');
  await fs.mkdir(liveDir);
  await fs.writeFile(path.join(liveDir, 'config.json'), JSON.stringify({ lastKnownAccountUuid: 'account-a', 'oauth:tokenCacheV2': { secret: 'NEVER_RENDER' } }));
  await fs.writeFile(path.join(liveDir, 'Cookies'), Buffer.from([0,1,2,3,254,255]));
  let running = true, opens = 0, quits = 0;
  const adapter = { status: async () => ({ running, installed: true }), quit: async () => { quits++; running = false; }, open: async () => { opens++; running = true; }, ...overrides };
  const desktop = await new DesktopProfiles({ dataDir, liveDir, adapter }).init();
  return { desktop, liveDir, dataDir, root, adapter, counts: () => ({ opens, quits }) };
}
test('desktop switches whole profiles in both directions with exact original bytes and no token exposure', async t => {
  const f = await fixture(t);
  const before = await fs.readFile(path.join(f.liveDir, 'config.json'));
  const cookies = await fs.readFile(path.join(f.liveDir, 'Cookies'));
  const id = await f.desktop.create('Work');
  assert.equal(f.desktop.state.activeId, 'original');
  assert.equal((await f.desktop.snapshot()).profiles.length, 2);
  assert.ok(!JSON.stringify(await f.desktop.snapshot()).includes('NEVER_RENDER'));
  await f.desktop.apply(id);
  assert.equal(f.desktop.state.activeId, id);
  assert.deepEqual(await fs.readdir(f.liveDir), []);
  assert.deepEqual(await fs.readFile(path.join(f.desktop.stored('original'), 'Cookies')), cookies);
  await fs.writeFile(path.join(f.liveDir, 'config.json'), JSON.stringify({ lastKnownAccountUuid: 'account-b' }));
  await f.desktop.apply('original');
  assert.deepEqual(await fs.readFile(path.join(f.liveDir, 'config.json')), before);
  assert.deepEqual(await fs.readFile(path.join(f.liveDir, 'Cookies')), cookies);
  const snapshot = await f.desktop.snapshot();
  assert.equal(snapshot.profiles.find(p => p.id === id).accountId, 'account-b');
  assert.deepEqual(f.counts(), { opens: 2, quits: 2 });
  assert.equal(snapshot.recoveryRequired, false);
});
test('refused graceful quit never changes either profile', async t => {
  const f = await fixture(t, { quit: async () => { throw new Error('User canceled quit'); } });
  const id = await f.desktop.create('Work');
  await assert.rejects(f.desktop.apply(id), /User canceled/);
  assert.equal(f.desktop.state.activeId, 'original');
  assert.ok(await fs.stat(path.join(f.liveDir, 'Cookies')));
  await assert.rejects(fs.stat(f.desktop.stored('original')));
});
test('failed target rename rolls back the original directory and clears journal', async t => {
  const f = await fixture(t);
  const id = await f.desktop.create('Work');
  f.desktop.rename = async (from, to) => { if (from === f.desktop.stored(id)) throw new Error('Injected disk failure'); return fs.rename(from, to); };
  await assert.rejects(f.desktop.apply(id), /Injected disk failure/);
  assert.equal(f.desktop.state.activeId, 'original');
  assert.ok(await fs.stat(path.join(f.liveDir, 'Cookies')));
  assert.equal((await f.desktop.snapshot()).recoveryRequired, false);
});
test('recovery recognizes installed target after a crash and refuses unexpected live data', async t => {
  const f = await fixture(t);
  const id = await f.desktop.create('Work');
  await f.adapter.quit();
  const a = await fs.stat(f.liveDir), b = await fs.stat(f.desktop.stored(id));
  const journal = { fromId: 'original', toId: id, fromIdentity: `${a.dev}:${a.ino}`, targetIdentity: `${b.dev}:${b.ino}` };
  await fs.writeFile(f.desktop.journalFile, JSON.stringify(journal));
  await fs.rename(f.liveDir, f.desktop.stored('original'));
  await fs.rename(f.desktop.stored(id), f.liveDir);
  await f.desktop.recoverStopped();
  assert.equal(f.desktop.state.activeId, id);
  await fs.writeFile(f.desktop.journalFile, JSON.stringify({ ...journal, targetIdentity: 'unexpected' }));
  await assert.rejects(f.desktop.recoverStopped(), /Không ghi đè/);
  assert.ok(await fs.stat(f.desktop.journalFile));
});
test('opening the active profile never quits, and launch failure leaves committed selection recoverable', async t => {
  const f = await fixture(t);
  await f.desktop.apply('original');
  assert.deepEqual(f.counts(), { opens: 1, quits: 0 });
  const id = await f.desktop.create('Work');
  f.adapter.open = async () => { throw new Error('Launch unavailable'); };
  const result = await f.desktop.apply(id);
  assert.equal(result.opened, false);
  assert.equal(result.changed, true);
  assert.equal(f.desktop.state.activeId, id);
  assert.equal((await f.desktop.snapshot()).recoveryRequired, false);
});
