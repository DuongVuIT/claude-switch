test('regression: an empty account must not replace the visible session library or quit Claude', async t => {
  const f = await fixture(t);
  const dir = path.join(f.liveDir, 'claude-code-sessions', 'account-a', 'org-a');
  await fs.mkdir(dir, { recursive: true });
  const session = { sessionId: 'local_11111111-1111-4111-8111-111111111111', title: 'Keep visible' };
  const file = path.join(dir, `${session.sessionId}.json`);
  await fs.writeFile(file, JSON.stringify(session));
  const id = await f.desktop.create('Empty account');
  const before = await fs.readFile(path.join(f.liveDir, 'config.json'));
  const snapshot = await f.desktop.snapshot();
  assert.match(snapshot.profiles.find(p => p.id === id).switchBlockReason, /thiếu 1 session/);
  await assert.rejects(f.desktop.apply(id), /thiếu 1 session/);
  assert.deepEqual(f.counts(), { opens: 0, quits: 0 });
  assert.equal(f.desktop.state.activeId, 'original');
  assert.deepEqual(await fs.readFile(path.join(f.liveDir, 'config.json')), before);
  assert.ok(await fs.stat(file));
  assert.equal((await f.desktop.snapshot()).recoveryRequired, false);
  // Even copying a matching session ID cannot establish another account's access.
  const other = path.join(f.desktop.stored(id), 'claude-code-sessions', 'account-b', 'org-b');
  await fs.mkdir(other, { recursive: true });
  await fs.writeFile(path.join(other, `${session.sessionId}.json`), JSON.stringify(session));
  await fs.writeFile(path.join(f.desktop.stored(id), 'config.json'), JSON.stringify({ lastKnownAccountUuid: 'account-b' }));
  await assert.rejects(f.desktop.apply(id), /Chưa xác minh quyền/);
  assert.deepEqual(f.counts(), { opens: 0, quits: 0 });
});
test('carryHistory rotates profiles while retaining transcripts and target credentials', async t => {
  const f = await fixture(t);
  const id = await f.desktop.create('Personal');
  const account = '22222222-2222-4222-8222-222222222222', org = '33333333-3333-4333-8333-333333333333';
  const cli = '44444444-4444-4444-8444-444444444444', sessionId = 'local_55555555-5555-4555-8555-555555555555';
  const target = f.desktop.stored(id);
  await fs.writeFile(path.join(target, 'config.json'), JSON.stringify({lastKnownAccountUuid:account, credential:'target-only'}));
  const relative = path.join('claude-code-sessions', account, org);
  await fs.mkdir(path.join(target, relative), {recursive:true});
  await fs.mkdir(path.join(f.liveDir, relative), {recursive:true});
  await fs.writeFile(path.join(f.liveDir, relative, sessionId+'.json'), JSON.stringify({sessionId,cliSessionId:cli,cwd:f.root,title:'Continue me',spawnSeed:'PRIVATE'}));
  f.desktop.transcriptRoot = path.join(f.root,'transcripts');
  await fs.mkdir(path.join(f.desktop.transcriptRoot,'project'), {recursive:true});
  const transcript = path.join(f.desktop.transcriptRoot,'project',cli+'.jsonl');
  await fs.writeFile(transcript,'original history');
  const result = await f.desktop.apply(id,{carryHistory:true});
  assert.equal(result.transfer.added,1);
  assert.equal(f.desktop.state.activeId,id);
  assert.equal(JSON.parse(await fs.readFile(path.join(f.liveDir,'config.json'))).credential,'target-only');
  assert.equal(JSON.parse(await fs.readFile(path.join(f.liveDir,relative,sessionId+'.json'))).spawnSeed,undefined);
  assert.equal(await fs.readFile(transcript,'utf8'),'original history');
  assert.deepEqual(f.counts(),{opens:1,quits:1});
});
